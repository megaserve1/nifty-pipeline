def draw(pdf, heading, lines):
    """split onto as many pages as the text needs -- nothing is ever silently cut."""
    PER_PAGE = 50
    chunks, cur, n = [], [], 0
    for ln in lines:
        cost = 2 if ln.startswith("# ") else 1
        if n + cost > PER_PAGE:
            chunks.append(cur); cur, n = [], 0
        cur.append(ln); n += cost
    if cur:
        chunks.append(cur)
    for i, c in enumerate(chunks):
        _page(pdf, heading, c, cont=i > 0)


