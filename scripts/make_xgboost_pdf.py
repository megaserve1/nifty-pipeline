def _page(pdf, heading, lines, cont=False):
    """one A4 page. fig.text() throughout -- ax.plot() autoscales the axes and silently moves
    every coordinate after it, which is what blanked the first build of this document."""
    fig = plt.figure(figsize=(8.27, 11.69))
