"""scripts/dataset_catalogue.py -- what every dataset version is, and where its bytes live.

WHY THIS EXISTS
    DVC is CONTENT-ADDRESSED: it stores a file under its own md5, not its name. So v7.2 sits at
        gs://<bucket>/final_pipeline/dvc/files/md5/b6/5988d72b619641c5c07f9b67c4a936
    and the string "v7.2" appears nowhere in the bucket. Someone browsing GCS sees hashes and
    cannot tell v1 from v9.

    That is deliberate -- identical bytes are stored once, and the path IS the checksum, so a file
    cannot be altered without the path changing. The cost is that the bucket is not browsable.

    THE NAME LIVES IN GIT. Every datasets/vN/dataset_vN.parquet.dvc holds the md5. git is the
    catalogue, the bucket is the blob store. This script prints that catalogue.

RUN
    final_venv/bin/python scripts/dataset_catalogue.py              # table on screen
    final_venv/bin/python scripts/dataset_catalogue.py --out docs/DATASET_VERSIONS.md
    final_venv/bin/python scripts/dataset_catalogue.py --paths      # just version -> gs:// path
"""
import argparse
import json
import pathlib
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import config as C   # noqa: E402


def dvc_remote() -> str:
    """the bucket path DVC pushes to, read from .dvc/config -- never hard-coded."""
    cfg = C.ROOT / ".dvc" / "config"
    if not cfg.exists():
        return ""
    url = ""
    for line in cfg.read_text().splitlines():
        s = line.strip()
        if s.startswith("url"):
            url = s.split("=", 1)[-1].strip()
    return url


def rows() -> list:
    out = []
    for d in sorted((C.ROOT / "datasets").glob("v*")):
        r = {"version": d.name, "md5": "", "bucket": "", "size_mb": None, "rows": None,
             "features": None, "categorical": None, "labels": "", "built": "", "status": ""}

        man = d / "manifest.json"
        if man.exists():
            m = json.loads(man.read_text())
            if isinstance(m, list):
                m = m[0]
            r["rows"] = m.get("rows")
            r["features"] = m.get("n_features") or len(m.get("feature_columns") or []) or None
            r["categorical"] = len(m.get("categorical_columns") or []) or None
            r["labels"] = m.get("labels_name") or ""
            r["built"] = str(m.get("built_at", ""))[:10]
            r["status"] = m.get("status", "")

        dvc = list(d.glob("*.dvc"))
        if dvc:
            o = (yaml.safe_load(dvc[0].read_text()) or {}).get("outs") or [{}]
            md5 = str(o[0].get("md5", ""))
            r["md5"] = md5
            r["size_mb"] = round(float(o[0].get("size", 0)) / 1e6, 1)
            if md5:
                r["bucket"] = f"{dvc_remote()}/files/md5/{md5[:2]}/{md5[2:]}"
        else:
            pq = list(d.glob("*.parquet"))
            if pq:
                r["size_mb"] = round(pq[0].stat().st_size / 1e6, 1)
            # NO .dvc POINTER = NOT IN THE BUCKET. it exists on one laptop and nowhere else.
            r["bucket"] = "NOT PUSHED -- local only"
        out.append(r)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="", help="write a markdown catalogue here")
    ap.add_argument("--paths", action="store_true", help="print only version -> gs:// path")
    a = ap.parse_args()
    rs = rows()

    if a.paths:
        for r in rs:
            print(f"{r['version']:<12} {r['bucket']}")
        return 0

    hdr = f"  {'version':<12}{'rows':>10}{'feat':>6}{'cat':>5}{'labels':>8}{'MB':>8}  {'built':<11}where"
    print(hdr)
    print("  " + "-" * (len(hdr) + 24))
    for r in rs:
        where = r["bucket"] if r["bucket"].startswith("NOT") else (
            ".../md5/" + r["md5"][:2] + "/" + r["md5"][2:10] + "..." if r["md5"] else "-")
        print(f"  {r['version']:<12}{(f'{r[chr(114)+chr(111)+chr(119)+chr(115)]:,}' if r['rows'] else '-'):>10}"
              f"{str(r['features'] or '-'):>6}{str(r['categorical'] or '-'):>5}"
              f"{str(r['labels'] or '-'):>8}{str(r['size_mb'] or '-'):>8}  {r['built'] or '-':<11}{where}")

    missing = [r["version"] for r in rs if r["bucket"].startswith("NOT")]
    if missing:
        print(f"\n  !! NOT IN THE BUCKET: {', '.join(missing)}")
        print(f"     these exist on this disk only. if it dies they are gone. run:")
        print(f"     dvc add datasets/<v>/dataset_<v>.parquet && dvc push")

    if a.out:
        p = pathlib.Path(a.out)
        p.parent.mkdir(parents=True, exist_ok=True)
        L = ["# Dataset versions", "",
             "DVC stores files by content hash, so the bucket has no version names in it.",
             "This table is the map. Generated by `scripts/dataset_catalogue.py`.", "",
             "| version | rows | features | categorical | labels | MB | built | bucket path |",
             "|---|---|---|---|---|---|---|---|"]
        for r in rs:
            L.append(f"| {r['version']} | {r['rows'] or '-'} | {r['features'] or '-'} | "
                     f"{r['categorical'] or '-'} | {r['labels'] or '-'} | {r['size_mb'] or '-'} | "
                     f"{r['built'] or '-'} | `{r['bucket'] or '-'}` |")
        L += ["", "## Getting one",
              "", "With the repo (normal way -- you never see a hash):", "",
              "```bash", "git clone https://github.com/megaserve1/nifty-pipeline.git",
              "cd nifty-pipeline", "dvc pull datasets/v7/dataset_v7.parquet.dvc", "```",
              "", "With only GCS read access: copy the bucket path from the table above.",
              "The file arrives named as its hash -- rename it to the version.", ""]
        p.write_text("\n".join(L))
        print(f"\n  wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
